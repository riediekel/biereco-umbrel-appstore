#!/usr/bin/env python3
# Rebuilds biereco-homepage/hooks/pre-start from the shipped sources.
#
# Run it from the repository root and commit the result:
#
#   python3 scripts/build-homepage-hook.py
#
# umbrelOS gives an installed app only its own package entries (umbrel-app.yml,
# docker-compose.yml, hooks/, data/, settings.yml, app-gateway.json), and it keeps
# that app's data folder when it updates an app. So the config files and the tile
# generator that reach an ALREADY INSTALLED app can only come from a hook that runs
# on the device: this hook is generated from the readable sources in the app package
# (scripts/generate.mjs and data/homepage/*.yaml) and carries their bytes, so an
# update replaces them and keeps your own edits as <name>.pre-<version>.

from pathlib import Path
import subprocess

APP = Path("biereco-homepage")
HOOK = APP / "hooks" / "pre-start"
SOURCES = [
    ("docker.yaml", APP / "data" / "homepage" / "docker.yaml"),
    ("settings.yaml", APP / "data" / "homepage" / "settings.yaml"),
    ("widgets.yaml", APP / "data" / "homepage" / "widgets.yaml"),
    ("bookmarks.yaml", APP / "data" / "homepage" / "bookmarks.yaml"),
    ("app-ports.yaml", APP / "data" / "homepage" / "app-ports.yaml"),
    ("services.yaml", APP / "data" / "homepage" / "services.yaml"),
    ("generate.mjs", APP / "scripts" / "generate.mjs"),
]

bodies = {}
for name, path in SOURCES:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
    delim = "SEEDED_" + name.replace(".", "_")
    if any(line.strip() == delim for line in text.split("\n")):
        raise SystemExit(f"{path} contains a line equal to {delim}; pick another delimiter")
    bodies[name] = text

header = f"""#!/bin/sh
# pre-start: put this app's config files and tile generator into its data folder.
#
# GENERATED by scripts/build-homepage-hook.py at the repository root, from
# biereco-homepage/scripts/generate.mjs and biereco-homepage/data/homepage/*.yaml.
# Edit those sources and run the builder again; do not edit this file.
#
# Why the files are carried here at all: umbrelOS hands an installed app only its own
# package entries, and it keeps that app's data folder when it updates an app, so a
# new version of this app would otherwise keep running the generator and the config
# files that the older version left behind. Files you had changed are kept next to
# their replacement as <name>.pre-<version>.
set -eu
"""

body = """
# umbrelOS runs a lifecycle hook on the device, with the app package as its location.
# Take that directory from APP_DIR or the working directory rather than guessing it.
APP_DIR=""
for candidate in ${APP_DIR:-} . "$(dirname "${BASH_SOURCE:-$0}")/.." ..; do
  if [ -f "${candidate}/umbrel-app.yml" ]; then
    APP_DIR=$(readlink -f "${candidate}")
    break
  fi
done

if [ -z "$APP_DIR" ]; then
  echo "pre-start: could not find the app package, leaving its data folder alone" >&2
  exit 0
fi

APP_DATA_DIR="$APP_DIR/data"
CFG_DIR="$APP_DATA_DIR/homepage"
SCRIPT_DIR="$APP_DATA_DIR/scripts"
SCRIPT_RUN="$SCRIPT_DIR/generate.mjs"
MARKER="$CFG_DIR/.seeded"

VERSION=$(sed -n 's/^version:[[:space:]]*"\\{0,1\\}\\([0-9.]\\{1,\\}\\)".*/\\1/p' "$APP_DIR/umbrel-app.yml")
SEEDED=$(cat "$MARKER" 2>/dev/null || true)

write_seeds() {
  mkdir -p "$CFG_DIR" "$SCRIPT_DIR"
  for f in docker.yaml settings.yaml widgets.yaml bookmarks.yaml app-ports.yaml services.yaml; do
    if [ -f "$CFG_DIR/$f" ]; then
      mv "$CFG_DIR/$f" "$CFG_DIR/$f.pre-$VERSION"
    fi
  done
  if [ -f "$SCRIPT_RUN" ]; then
    mv "$SCRIPT_RUN" "$SCRIPT_RUN.pre-$VERSION"
  fi
"""

for name, _path in SOURCES:
    target = "$SCRIPT_RUN" if name == "generate.mjs" else f"$CFG_DIR/{name}"
    delim = "SEEDED_" + name.replace(".", "_")
    body += f'''
  cat > "{target}" <<'{delim}'
{bodies[name]}
{delim}
'''

body += """}

if [ -z "$VERSION" ]; then
  echo "pre-start: no version in umbrel-app.yml, leaving the data folder as it is" >&2
elif [ "$SEEDED" = "$VERSION" ]; then
  echo "pre-start: config and generator for $VERSION already in place, keeping your edits"
else
  write_seeds
  printf '%s\\n' "$VERSION" > "$MARKER"
  echo "pre-start: seeded Homepage config and generator for $VERSION"
fi

# Homepage and its sync service write config as uid 1000.
chown -R 1000:1000 "$APP_DATA_DIR"
"""

hook = (header + body).replace("\r\n", "\n")
HOOK.write_text(hook, encoding="utf-8", newline="\n")
sizes = ", ".join(f"{name} {len(bodies[name])}" for name, _ in SOURCES)
print(f"wrote {HOOK} ({len(hook)} bytes): {sizes}")
subprocess.run(["bash", "-n", str(HOOK).replace("\\", "/")], check=True)
print("bash -n: the generated hook parses")
